  /// إرجاع معرف التصنيف الحقيقي للخادم بناءً على القسم الرئيسي والفرعي
  static int resolveCategoryId(String mainSection, [String? subSection]) {
    if (subSection != null && subCategoryIds[mainSection] != null) {
      final exact = subCategoryIds[mainSection]![subSection];
      if (exact != null) return exact;

      // بحث جزئي مرن
      for (final entry in subCategoryIds[mainSection]!.entries) {
        if (subSection.contains(entry.key) || entry.key.contains(subSection)) {
          return entry.value;
        }
      }
    }
    return mainCategoryIds[mainSection] ?? 2;
  }

  /// إرجاع قائمة المعرفات المقبولة لقسم فرعي معين (شاملاً القسم الأب عند الحاجة)
  static Set<int> acceptedIdsFor(String mainSection, String subSection) {
    final id = resolveCategoryId(mainSection, subSection);
    return {id};
  }

  /// التحقق هل الحلقة القادمة من السيرفر تنتمي إلى القسم الرئيسي/الفرعي المحدد
  static bool matchesClass(
    Map<String, dynamic> cls, {
    required String mainSection,
    required String subSection,
  }) {
    final targetId = resolveCategoryId(mainSection, subSection);
    final catObj = cls['category'];
    final clsCatId = cls['category_id'] is int
        ? cls['category_id'] as int
        : int.tryParse('${cls['category_id'] ?? catObj?['id'] ?? ''}');

    if (clsCatId != null && clsCatId == targetId) {
      return true;
    }

    final clsCatName = catObj?['name']?.toString().trim() ?? '';
    if (clsCatName.isNotEmpty) {
      if (clsCatName == subSection ||
          subSection.contains(clsCatName) ||
          clsCatName.contains(subSection)) {
        // تحقق من عدم الخلط بين حفظ الصغار في القرآن وحفظ الصغار في السنة النبوية
        final parentId = catObj?['parent_id'];
        if (parentId == 128 && mainSection != 'السنة النبوية') return false;
        if (parentId == 21 && mainSection != 'القرآن الكريم') return false;
        return true;
      }
    }

    return false;
  }
